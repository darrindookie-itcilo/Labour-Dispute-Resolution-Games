import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import * as rules from '../lib/game/engine.mjs';
const DATA=JSON.parse(fs.readFileSync('lib/game/data.json','utf8'));
const source=fs.readFileSync('ui/app.js','utf8');
const memory=new Map();
const storage=map=>({getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,String(v)),removeItem:k=>map.delete(k)});
const localStorage=storage(memory);
const dx=rules.newGame(DATA,'diagnostic',{seed:'workshop-2026'},'Test1');
const es=rules.newGame(DATA,'escalation',{},'Table 3');
localStorage.setItem('ldg-practice-v2',JSON.stringify({diagnostic:dx,escalation:es}));
localStorage.setItem('ldg-connections-v2',JSON.stringify([{team:{id:'qa',name:'QA Team A',state:dx},room:{code:'ABCDEFGH'}},{team:{id:'real',name:'Table 2',state:dx},room:{code:'JKLMNPQR'}}]));
localStorage.setItem('ldg-imports-v2',JSON.stringify([es]));
localStorage.setItem('unrelated-app','keep me');
function app(){
 const events={},session=new Map([['ldg-admin-v2','test-session-only']]);
 const nodes=new Map();
 const node=id=>{if(!nodes.has(id))nodes.set(id,{innerHTML:'',textContent:'',classList:{add(){},remove(){},toggle(){}},setAttribute(){},addEventListener(){},querySelectorAll(){return []},querySelector(){return null},focus(){}});return nodes.get(id)};
 const context=vm.createContext({DATA,...rules,localStorage,sessionStorage:storage(session),document:{getElementById:node,querySelectorAll:()=>[],hidden:false},location:{hash:'#hub',search:''},window:{addEventListener:(name,fn)=>events[name]=fn,scrollTo(){}},crypto,URLSearchParams,URL,Date,setInterval(){},setTimeout(){},clearTimeout(){},console});
 vm.runInContext(source.replace(/\}\)\(\);\s*$/,`window.test={savedHTML,setup,login,clearSavedGames,persist,testTeamName,defaultTeam,getState:()=>({practices,connections,live:ui.live})};})();`),context);
 return {api:context.window.test,events,session,main:node('main')};
}
let checks=0;
function ok(value,message){assert.ok(value,message);checks++}
const first=app(),second=app();
const html=first.main.innerHTML;
ok(!html.includes('Resume Test1'),'Old test practice hidden');
ok(!html.includes('Resume QA Team A'),'Old QA connection hidden');
ok(html.includes('Resume Table 3'),'Real practice remains visible');
ok(html.includes('Resume Table 2'),'Real team connection remains visible');
ok(html.includes('Clear saved games'),'Clear control is visible');
ok(html.includes('id="join-name" maxlength="40" value="Team 1"'),'Live join defaults to Team 1');
ok(first.api.setup('diagnostic').includes('value="Team 1"'),'Hidden QA name does not prefill practice');
ok(first.api.setup('escalation').includes('value="Table 3"'),'Real practice name is retained');
for(const name of ['QA Campaign','qa-team','Test1','test demo','Deployment Check 2'])ok(first.api.testTeamName(name),'QA name hidden: '+name);
for(const name of ['Qatar','Testimony','Quality Assurance','Table 2'])ok(!first.api.testTeamName(name),'Real name retained: '+name);
ok(first.api.login().includes('Darrin Dookie’s ChatGPT Sites project'),'Login identifies service owner');
ok(first.api.login().includes('labour-dispute-games.darrin-dookie.chatgpt.site'),'Login identifies destination');
first.api.clearSavedGames();first.api.persist();
ok(localStorage.getItem('ldg-practice-v2')==='{}','Local practice cleared');
ok(localStorage.getItem('ldg-connections-v2')==='[]','Saved live connections cleared');
ok(localStorage.getItem('ldg-imports-v2')===JSON.stringify([es]),'Imported reports preserved');
ok(localStorage.getItem('unrelated-app')==='keep me','Other GitHub Pages applications preserved');
ok(first.session.get('ldg-admin-v2')==='test-session-only','Facilitator authentication preserved');
second.events.storage({key:'ldg-saved-cleared-v2'});second.events.beforeunload();
ok(localStorage.getItem('ldg-practice-v2')==='{}','Other open tab cannot restore cleared practice');
ok(localStorage.getItem('ldg-connections-v2')==='[]','Other open tab cannot restore cleared connections');
console.log(`${checks} UI storage checks passed: defaults, QA filtering, scoped clearing, credentials and other open tabs.`);
